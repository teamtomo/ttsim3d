"""Regression test: simulate a full ribosomal subunit and compare to a reference.

NOTE: If the simulation algorithm changes intentionally, regenerate the
reference volume (the simulated volume of each run is saved next to the
downloaded files) and publish it under ``REFERENCE_MRC_URL``.
"""

import os
import subprocess
from pathlib import Path

import mrcfile
import numpy as np
import pytest
import requests
import torch

from ttsim3d import Simulator

PDB_URL = "https://zenodo.org/records/15685978/files/parsed_6Q8Y_whole_LSU_match3.pdb?download=1"
# TODO: publish the reference volume generated by ttsim3d >= 0.5 (volts,
# monorepo-based pipeline) and set its URL here. The previous reference
# (parsed_6Q9Y_whole_LSU_match3_48af52b.mrc) used cisTEM units and B-factor
# conventions and is no longer comparable.
REFERENCE_MRC_URL: str | None = None

TMP_DIR = Path(__file__).resolve().parent / "tmp"


def download_file(url: str, dest_folder: Path) -> Path:
    """Download ``url`` into ``dest_folder`` unless it already exists."""
    dest_folder.mkdir(parents=True, exist_ok=True)
    path = dest_folder / url.split("/")[-1].split("?")[0]
    if path.exists():
        return path

    response = requests.get(url, stream=True, timeout=60)
    response.raise_for_status()
    with open(path, "wb") as file:
        for chunk in response.iter_content(1 << 20):
            file.write(chunk)
    return path


def git_commit_hash() -> str:
    """Short hash of the current commit, or 'unknown'."""
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "unknown"
    return result.stdout.strip()


def reference_simulator(pdb_path: Path) -> Simulator:
    """The settings used to generate the reference volume."""
    return Simulator(
        structure={"path": pdb_path},
        pixel_spacing=0.95,
        volume_shape=(400, 400, 400),
        dose_filter={"start": 0.0, "end": 50.0},
        mtf="k2_300kv",
    )


@pytest.mark.skipif(
    os.environ.get("CI", "false").lower() == "true",
    reason="Needs ~20 GB of memory; run locally or on a large runner.",
)
@pytest.mark.skipif(REFERENCE_MRC_URL is None, reason="Reference not yet published.")
def test_simulated_volume_matches_reference():
    pdb_path = download_file(PDB_URL, TMP_DIR)
    reference_path = download_file(str(REFERENCE_MRC_URL), TMP_DIR)

    device = "cuda:0" if torch.cuda.is_available() else "cpu"
    volume = reference_simulator(pdb_path).run(device=device).cpu().numpy()

    with mrcfile.new(TMP_DIR / f"simulated_volume_{git_commit_hash()}.mrc", True) as m:
        m.set_data(volume.astype(np.float32))

    with mrcfile.open(reference_path) as reference:
        assert volume.shape == reference.data.shape
        scale = np.abs(reference.data).max()
        np.testing.assert_allclose(volume, reference.data, atol=1e-4 * scale)
